def test_contract_conversion_keeps_confidence_null(tmp_path: Path) -> None:
    pages = [_two_lines(), PageSpec(images=[Image(0, 0, *LETTER)]), _two_lines(rotate=90, crop_box=(0, 300, 612, 792))]
    path = write_pdf(tmp_path / "c.pdf", pages, page_labels="<< /Nums [0 << /S /D /St 10 >>] >>")
    extraction = extract_native_pdf(path)
    doc = to_contract_document(extraction, source_uri="asset://test/c.pdf", title="Synthetic")

    assert isinstance(doc, Document)
    assert [p.page_label for p in doc.pages] == ["10", "11", "12"]
    assert doc.source_asset.sha256 == extraction.sha256
    assert len(doc.blocks) == 4  # 2 lines on page 0, none on the image page, 2 on page 2
    for block in doc.blocks:
        assert block.confidence.score is None
        assert block.confidence.origin is ConfidenceOrigin.NOT_AVAILABLE
        assert block.confidence.reason
        assert block.raw_text == block.current_text and block.revision == 1
        assert block.provenance.method.value == "native_pdf_text"
        assert block.provenance.engine_version == extraction.engine_version

    payload = json.loads(doc.model_dump_json())
    jsonschema.Draft202012Validator(build_json_schema(), format_checker=jsonschema.FormatChecker()).validate(payload)
    assert Document.model_validate(payload) == doc


