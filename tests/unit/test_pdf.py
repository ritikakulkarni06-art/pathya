LETTER = (612.0, 792.0)


def _two_lines(**kwargs: object) -> PageSpec:
    return PageSpec(texts=[Text(72, 700, "Hello world"), Text(72, 680, "Second line")], **kwargs)  # type: ignore[arg-type]


def _all_boxes_valid(extraction) -> None:  # type: ignore[no-untyped-def]
    for page in extraction.pages:
        for word in page.words:
            if word.bbox is not None:
                validate_normalized_bbox(word.bbox)
        for line in page.lines:
            if line.bbox is not None:
                validate_normalized_bbox(line.bbox)


