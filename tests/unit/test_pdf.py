def test_files_are_released_after_success_and_failure(tmp_path: Path) -> None:
    # On Windows an open handle prevents deletion, so unlink proves handles were closed.
    ok = write_pdf(tmp_path / "ok.pdf", [_two_lines(), _two_lines()])
    extract_native_pdf(ok)
    render_page(ok, 0, dpi=36)
    iterator = iter_rendered_pages(ok, dpi=36)
    next(iterator)
    iterator.close()  # early stop must close the PDFium document
    ok.unlink()

    bad = tmp_path / "bad.pdf"
    bad.write_bytes(b"%PDF-1.4\ngarbage")
    with pytest.raises(PdfMalformedError):
        extract_native_pdf(bad)
    with pytest.raises(PdfMalformedError):
        render_page(bad, 0)
    bad.unlink()

    limited = write_pdf(tmp_path / "lim.pdf", [_two_lines()])
    with pytest.raises(PdfLimitError):
        render_page(limited, 0, dpi=300, limits=PdfLimits(max_render_pixels=10))
    limited.unlink()


