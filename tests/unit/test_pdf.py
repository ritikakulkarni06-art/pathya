def test_normal_text_extraction(tmp_path: Path) -> None:
    path = write_pdf(tmp_path / "a.pdf", [_two_lines()])
    result = extract_native_pdf(path)
    page = result.pages[0]
    assert result.page_count == 1 and result.engine == "pdfplumber"
    assert [w.text for w in page.words] == ["Hello", "world", "Second", "line"]
    assert [line.text for line in page.lines] == ["Hello world", "Second line"]
    assert page.text == "Hello world\nSecond line"
    assert page.ocr.decision is OcrDecision.NATIVE_TEXT and not page.ocr.needs_ocr
    assert len(result.sha256) == 64 and result.file_bytes == path.stat().st_size


