def test_word_boxes_are_normalized_and_positioned(tmp_path: Path) -> None:
    page = extract_native_pdf(write_pdf(tmp_path / "w.pdf", [_two_lines()])).pages[0]
    hello = page.words[0]
    x0, top, x1, bottom = hello.bbox  # type: ignore[misc]
    assert x0 == pytest.approx(72 / 612, abs=1e-6)
    assert top == pytest.approx((792 - 709.5) / 792, abs=1e-3)
    assert bottom == pytest.approx((792 - 697.5) / 792, abs=1e-3)
    assert x0 < x1 and top < bottom
    assert hello.fontname and hello.fontname.endswith("Helvetica") and hello.glyph_height == pytest.approx(12)
    assert page.words[2].bbox[1] > hello.bbox[1]  # type: ignore[index]  # lower line is further down


def test_normalize_display_box_clip_outside_and_degenerate() -> None:
    visible = (50.0, 50.0, 150.0, 250.0)
    assert normalize_display_box((60, 70, 100, 90), visible) == ((0.1, 0.1, 0.5, 0.2), frozenset())
    box, notes = normalize_display_box((140, 60, 170, 80), visible)
    assert box == pytest.approx((0.9, 0.05, 1.0, 0.15)) and notes == {"clipped"}
    assert normalize_display_box((300, 300, 310, 310), visible) == (None, frozenset())
    box, notes = normalize_display_box((100, 100, 100, 120), visible)
    assert notes == {"degenerate"} and box[0] < box[2]  # type: ignore[index]
    with pytest.raises(ValueError):
        validate_normalized_bbox((0.2, 0.1, 0.1, 0.3))


ROTATIONS = [0, 90, 180, 270]


@pytest.mark.parametrize("rotation", ROTATIONS)
def test_rotated_pages_keep_words_and_map_back(tmp_path: Path, rotation: int) -> None:
    reference = extract_native_pdf(write_pdf(tmp_path / "r0.pdf", [_two_lines()])).pages[0]
    page = extract_native_pdf(write_pdf(tmp_path / "r.pdf", [_two_lines(rotate=rotation)])).pages[0]
    assert page.rotation.value == rotation
    assert (page.width, page.height) == (LETTER if rotation in (0, 180) else LETTER[::-1])
    assert [w.text for w in page.words] == ["Hello", "world", "Second", "line"]
    assert sorted(line.text for line in page.lines) == ["Hello world", "Second line"]
    for word, ref in zip(page.words, reference.words):
        back = normalized_to_pdf_user_space(word.bbox, page.transform)  # type: ignore[arg-type]
        expected = normalized_to_pdf_user_space(ref.bbox, reference.transform)  # type: ignore[arg-type]
        assert back == pytest.approx(expected, abs=0.01)


@pytest.mark.parametrize("rotation", ROTATIONS)
def test_counter_rotated_text_reads_upright(tmp_path: Path, rotation: int) -> None:
    # Common in scanned PDFs: the page is rotated and the text layer counter-rotated.
    origins = {0: (100, 600), 90: (300, 200), 180: (500, 300), 270: (300, 600)}
    x, y = origins[rotation]
    spec = PageSpec(texts=[upright_text(rotation, x, y, "Upright words here")], rotate=rotation)
    page = extract_native_pdf(write_pdf(tmp_path / "u.pdf", [spec])).pages[0]
    assert [w.text for w in page.words] == ["Upright", "words", "here"]
    assert page.text == "Upright words here"
    assert all(w.upright for w in page.words)
    xs = [w.bbox[0] for w in page.words]  # type: ignore[index]
    assert xs == sorted(xs)  # left-to-right on the displayed page


@pytest.mark.parametrize("rotation", ROTATIONS)
def test_cropped_pages(tmp_path: Path, rotation: int) -> None:
    crop = (50.0, 400.0, 562.0, 750.0)
    spec = PageSpec(texts=[Text(72, 700, "Inside"), Text(72, 100, "Outside"), Text(540, 600, "Edgeword")],
                    crop_box=crop, rotate=rotation)
    page = extract_native_pdf(write_pdf(tmp_path / "c.pdf", [spec])).pages[0]
    assert page.transform.crop_box == crop
    assert sorted((page.width, page.height)) == [350.0, 512.0]
    by_text = {w.text: w for w in page.words}
    assert by_text["Outside"].bbox is None and "outside_visible_area" in by_text["Outside"].notes
    assert "clipped" in by_text["Edgeword"].notes
    assert {w.code for w in page.warnings} >= {"words_outside_crop", "words_clipped"}
    back = normalized_to_pdf_user_space(by_text["Inside"].bbox, page.transform)  # type: ignore[arg-type]
    assert back[0] == pytest.approx(72, abs=0.05) and back[1] == pytest.approx(697.5, abs=0.05)


def test_transform_round_trip_without_extraction() -> None:
    t = CoordinateTransform(source_space="pdf_user_space", crop_box=(0, 0, 612, 792), rotation_applied=0)
    assert normalized_to_pdf_user_space((0.0, 0.0, 1.0, 1.0), t) == (0, 0, 612, 792)
    for rotation in ROTATIONS:
        rt = CoordinateTransform(source_space="pdf_user_space", crop_box=(50, 300, 562, 750),
                                 rotation_applied=rotation)
        box = (0.1, 0.2, 0.4, 0.7)
        assert pdf_user_space_to_normalized(normalized_to_pdf_user_space(box, rt), rt) == pytest.approx(box)


