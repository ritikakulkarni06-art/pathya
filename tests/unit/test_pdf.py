@pytest.mark.parametrize("rotation", ROTATIONS)
def test_render_matches_extracted_geometry(tmp_path: Path, rotation: int) -> None:
    # A black rectangle drawn at known user-space coordinates on a cropped page.
    content = b"0 g 100 500 80 40 re f"
    spec = PageSpec(raw_content=content, rotate=rotation, crop_box=(50, 300, 562, 750))
    path = write_pdf(tmp_path / "rect.pdf", [spec])
    transform = extract_native_pdf(path).pages[0].transform
    expected = pdf_user_space_to_normalized((100, 500, 180, 540), transform)
    rendered = render_page(path, 0, dpi=72, grayscale=True)
    assert rendered.image.mode == "L"
    dark = np.argwhere(np.asarray(rendered.image) < 128)
    (py0, px0), (py1, px1) = dark.min(axis=0), dark.max(axis=0) + 1
    measured = (px0 / rendered.width_px, py0 / rendered.height_px, px1 / rendered.width_px, py1 / rendered.height_px)
    assert measured == pytest.approx(expected, abs=2 / min(rendered.width_px, rendered.height_px))
    assert rendered.transform.rotation_applied.value == rotation


